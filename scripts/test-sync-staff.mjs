import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { PGlite } from '@electric-sql/pglite';
import { readStaff, validateStaff, updateStaffQuery, connectionInfo, selectMatchingStaff } from './sync-staff.mjs';

const rows = [['email','name','active','staffType','staffFunction'], ['one@alumnos.udg.mx','One','SI','Alumno','Registro de asistencia'], ['two@academicos.udg.mx','Two','si','Académico','Apoyo operativo']];
const registrations = [['id'], ['EQ26-0000000001','','','one@alumnos.udg.mx','','Alumno','','','','Confirmado'], ['EQ26-0000000002','','','two@academicos.udg.mx','','Profesor','','','','Confirmado'], ['EQ26-0000000003','','','other@alumnos.udg.mx','','Alumno','','','','Confirmado']];
const context = vm.createContext({});
vm.runInContext(readFileSync(new URL('../google-apps-script/Code.gs', import.meta.url), 'utf8'), context);
context.getSpreadsheet_ = () => ({});
context.ensureSheet_ = (_, name) => ({ getDataRange: () => ({ getDisplayValues: () => name === 'Staff' ? rows : registrations }) });
const staff = JSON.parse(JSON.stringify(context.listStaffRegistrations_().staff));
assert.equal(staff.length, 2);
assert.equal(staff[0].staffFunction, 'Registro de asistencia');
assert.equal(staff.some(s => s.email.startsWith('other')), false);
assert.equal('qrToken' in staff[0], false);
assert.throws(() => validateStaff([...staff, staff[0]]));
assert.throws(() => validateStaff([{ ...staff[0], id: null }]));
let calls = 0;
await readStaff('https://example.invalid', 'secret', { sleep: async () => {}, log: () => {}, fetchImpl: async (_, options) => {
  assert.equal(JSON.parse(options.body).action, 'listStaffRegistrations');
  if (++calls === 1) throw new TypeError('network');
  return new Response(JSON.stringify({ ok: true, staff }));
} });
assert.equal(calls, 2);
calls = 0;
await assert.rejects(readStaff('https://example.invalid', 'secret', { sleep: async () => {}, log: () => {}, fetchImpl: async () => { calls++; return new Response('<html>login</html>'); } }));
assert.equal(calls, 1);
calls = 0;
await assert.rejects(readStaff('https://example.invalid', 'secret', { sleep: async () => {}, log: () => {}, fetchImpl: async () => { calls++; throw new TypeError('network'); } }));
assert.equal(calls, 3);
assert.equal(connectionInfo({ DATABASE_URL:'postgres://a:b@primary/db', POSTGRES_URL:'postgres://a:b@other/db' }).key, 'DATABASE_URL');
const db = new PGlite();
await db.exec(`CREATE TABLE participants (id text PRIMARY KEY, email text UNIQUE, status text, role text, staff_type text, staff_function text, updated_at timestamptz, qr_token text);
  INSERT INTO participants VALUES ('EQ26-0000000001','one@alumnos.udg.mx','Confirmado','Alumno',NULL,NULL,NOW(),'original-qr'), ('EQ26-0000000002','two@academicos.udg.mx','Confirmado','Profesor',NULL,NULL,NOW(),'qr-two'), ('EQ26-0000000003','other@alumnos.udg.mx','Confirmado','Alumno',NULL,NULL,NOW(),'qr-other');`);
const checked = validateStaff(staff);
const matchingRows = checked.map(p => ({...p, status: 'Confirmado'}));
assert.throws(() => selectMatchingStaff(checked, matchingRows.slice(1), false, () => {}));
assert.equal(selectMatchingStaff(checked, matchingRows.slice(1), true, () => {}).length, 1);
assert.throws(() => selectMatchingStaff(checked, matchingRows.map(p => ({...p, id: 'different'})), true, () => {}));
assert.throws(() => selectMatchingStaff(checked, matchingRows.map(p => ({...p, status: 'Cancelado'})), true, () => {}));
assert.equal((await db.query(updateStaffQuery, [JSON.stringify(checked)])).rows.length, 2);
assert.equal((await db.query(updateStaffQuery, [JSON.stringify(checked)])).rows.length, 2);
const saved = (await db.query('SELECT * FROM participants ORDER BY id')).rows;
assert.equal(saved[0].qr_token, 'original-qr');
assert.equal(saved[0].id, 'EQ26-0000000001');
assert.equal(saved[2].role, 'Alumno');
assert.equal((await db.query(updateStaffQuery, [JSON.stringify([...checked, {...checked[0],email:'missing@alumnos.udg.mx'}])])).rows.length, 0);
await db.close();
console.log('OK: Staff-only Apps Script, bounded retries, no bulk fallback, validation, atomic/idempotent update, QR/identity preserved. No external connections.');
